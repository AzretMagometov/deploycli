"""Имена ресурсов Traefik: сборка, проверка алфавита, приоритет роутера.

См. ADR-003 в decisions.md. Все имена, попадающие в пространство имён
Traefik на хосте, несут префикс пространства имён стека (обычно литерал
``${COMPOSE_PROJECT_NAME}``, подставляемый compose из ``.env`` контура).
Префикс не проверяется этим модулем по алфавиту сегмента — проверке
подлежат только сегменты, которыми владеет подключённый проект (имя
сервиса, имя обработчика). Настоящее значение префикса проверяет
предполётная проверка тем же ``validate_segment``.

Нарушение алфавита не нормализуется: два разных имени, приведённых к
одному, вернули бы ровно ту коллизию, ради устранения которой заведено
пространство имён (ADR-003). Нарушение останавливает генерацию
исключением.
"""

import re

COMPOSE_PROJECT_NAME_LITERAL = "${COMPOSE_PROJECT_NAME}"
"""Литерал префикса в сгенерированных файлах: подставляется compose, не генератором."""

_SEGMENT_ALPHABET = re.compile(r"[a-z][a-z0-9-]*")


class InvalidNameError(ValueError):
    """Сегмент имени нарушает алфавит ``^[a-z][a-z0-9-]*$``."""


def validate_segment(name: str) -> None:
    """Проверяет сегмент имени по алфавиту ``^[a-z][a-z0-9-]*$``.

    Поднимает :class:`InvalidNameError`, называющую имя нарушителя и
    требуемый алфавит, вместо того чтобы приводить имя к допустимому
    виду.
    """
    if not _SEGMENT_ALPHABET.fullmatch(name):
        raise InvalidNameError(f"Имя '{name}' вне алфавита [a-z][a-z0-9-]*")


def router_service_name(namespace: str, service: str) -> str:
    """Строит общее имя роутера и сервиса Traefik: ``<ns>-<сервис>``.

    Один публичный сервис даёт один роутер (ADR-003), поэтому оба
    ресурса делят одно и то же имя. ``namespace`` — префикс
    пространства имён стека, по алфавиту не проверяется; проверке
    подлежит только ``service``.
    """
    validate_segment(service)
    return f"{namespace}-{service}"


def hsts_handler_name(namespace: str) -> str:
    """Строит имя единственного в v1 обработчика HSTS: ``<ns>-hsts``.

    Обработчик один на весь стек и не привязан к конкретному сервису
    (ADR-003).
    """
    return f"{namespace}-hsts"


def router_priority(path_prefix: str = "") -> int:
    """Приоритет роутера: ``100 + длина префикса пути``, либо ``1`` без пути.

    Traefik ранжирует роутеры по длине правила автоматически, но этого
    не хватает при сочетании алиасов домена и разделения по префиксу
    пути на одном домене (ADR-003), поэтому приоритет пишется явно.
    """
    return 100 + len(path_prefix) if path_prefix else 1
